-- Run as the schema user exposed through ORDS.
-- SQL*Plus, SQLcl, and Oracle Database Actions recognize `/` as a block terminator.

begin
  execute immediate '
    create table keepalive_log (
      id number generated by default as identity primary key,
      ping_time timestamp with time zone default systimestamp not null,
      status varchar2(32 char) not null,
      request_id varchar2(36)
    )';
exception
  when others then
    if sqlcode != -955 then
      raise;
    end if;
end;
/

