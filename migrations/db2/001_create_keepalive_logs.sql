-- Run once in the service account's schema to initialize a new installation.
CREATE TABLE DB2_KEEPALIVE_LOGS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    PING_TIME TIMESTAMP(6) NOT NULL DEFAULT CURRENT TIMESTAMP,
    STATUS VARCHAR(32) NOT NULL,
    REQUEST_ID VARCHAR(36)
);
CREATE INDEX DB2_KEEPALIVE_LOGS_TIME_IDX ON DB2_KEEPALIVE_LOGS (PING_TIME DESC);
CREATE UNIQUE INDEX DB2_KEEPALIVE_REQUEST_ID
  ON DB2_KEEPALIVE_LOGS (REQUEST_ID) EXCLUDE NULL KEYS;
COMMENT ON COLUMN DB2_KEEPALIVE_LOGS.PING_TIME IS 'UTC; application inserts database UTC time explicitly';
