-- Run in the Supabase SQL editor as a project administrator.
-- The service uses a server-side secret key to access its log table.

create table if not exists public.my_keepalive_logs (
  id bigint generated by default as identity primary key,
  ping_time timestamptz not null default now(),
  status text not null
);

create index if not exists my_keepalive_logs_ping_time_idx
  on public.my_keepalive_logs (ping_time desc);

alter table public.my_keepalive_logs enable row level security;

revoke all on table public.my_keepalive_logs from anon, authenticated;

grant select, insert on table public.my_keepalive_logs to service_role;
grant usage, select on sequence public.my_keepalive_logs_id_seq to service_role;
